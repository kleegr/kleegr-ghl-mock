export type HelpArea = (typeof HELP_AREAS)[number];

export interface HelpEntry {
  /** Canonical `data-tour` key, e.g. `contacts.addButton`. Unique. */
  key: string;
  /** Functional area this element belongs to. */
  area: HelpArea;
  /** Granularity of the element: a whole screen, a section, or a single control. */
  tier: HelpTier;
  /** Short human label with no trailing punctuation, e.g. "Add Contact button". */
  label: string;
  /** Plain-language, business-value explanation shown in "What is this?". */
  help: string;
  /** Relative prominence for contextual-help affordances. Defaults to secondary. */
  importance?: HelpImportance;
  /** Runtime tutorial flow id (from flows.ts) that walks through this element. */
  tutorialId?: string;
  /** Part of the V1 explainability coverage target (screens, tutorial targets, primary shell). */
  requiredForV1?: boolean;
}

