/**
 * Help Content Model — the single source of truth for explainable UI.
 *
 * This catalog powers two things the owner asked for:
 *   1. Contextual "What is this?" help — click any explainable screen, section
 *      or control and read what it is *for* (not just what it is called).
 *   2. The canonical key list that guided tutorials, the help popover (Dev 2),
 *      and the anchor-instrumentation pass (Dev 5) all build on, so nobody has
 *      to guess key names.
 *
 * Design rules (kept deliberately simple):
 *   - `key` mirrors the `data-tour` attribute and follows `area.element`
 *     (lowercase area, camelCase element). The live `data-tour` attribute in
 *     the DOM remains the runtime source of truth; this file is the catalog
 *     of what *should* exist plus its plain-language meaning.
 *   - `help` explains the business value — what a real operator uses it for —
 *     never filler like "demo placeholder" or "button that opens a modal".
 *   - `requiredForV1` marks the keys that make up the V1 explainability
 *     coverage target (every screen, every guided-tutorial target, and the
 *     primary shell controls). Lower-priority sections/controls are seeded now
 *     but not required, so Developer 5 has a clear "must instrument" list
 *     without the checker hard-failing on keys that aren't placed yet.
 *
 * Apostrophes in prose use the typographic form (U+2019) on purpose: the
 * dependency-free checker parses single-quoted fields, and this keeps long
 * copy from terminating a string early — the same convention flows.ts uses.
 *
 * This module has zero runtime dependencies.
 */

// ─── Types ───────────────────────────────────────────────────────────────────

