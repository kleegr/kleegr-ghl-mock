// ─── Derived lookups & helpers ───────────────────────────────────────────────

/** All entries keyed by their canonical key. O(1) lookup for the help popover. */
export const helpByKey: Readonly<Record<string, HelpEntry>> = Object.fromEntries(
  HELP_CONTENT.map((e) => [e.key, e]),
);

/** Entries grouped by area, in catalog order. */
export const helpByArea = HELP_CONTENT.reduce(
  (acc, entry) => {
    (acc[entry.area] ??= []).push(entry);
    return acc;
  },
  {} as Record<HelpArea, HelpEntry[]>,
);

/** Keys that make up the V1 explainability coverage target. */
export const REQUIRED_V1_HELP_KEYS: readonly string[] = HELP_CONTENT.filter(
  (e) => e.requiredForV1,
).map((e) => e.key);

/** Look up a single help entry by key. */
export function getHelp(key: string | null | undefined): HelpEntry | undefined {
  if (!key) return undefined;
  return helpByKey[key];
}

/** Type guard — true when the string is a catalogued help key. */
export function isHelpKey(key: string): boolean {
  return Object.prototype.hasOwnProperty.call(helpByKey, key);
}
